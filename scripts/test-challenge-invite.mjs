import {JSDOM} from 'jsdom';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('public/index.html','utf8');
const script=fs.readFileSync('public/challenge-invite.js','utf8');
const key='autosim.challenge.dismissed.v27';
function setup({oldDismissed=false,newDismissed=false,storageBlocked=false}={}){
  const dom=new JSDOM(html,{url:'https://qa.test/#test-drive',runScripts:'outside-only',pretendToBeVisual:true});
  const w=dom.window, d=w.document;
  Object.defineProperty(w,'scrollY',{value:2000});
  if(oldDismissed)w.sessionStorage.setItem('autosim.challenge.dismissed.v14','1');
  if(newDismissed)w.localStorage.setItem(key,'1');
  if(storageBlocked)for(const name of ['localStorage','sessionStorage'])Object.defineProperty(w,name,{get(){throw new Error('Storage blocked');}});
  let start;w.setTimeout=fn=>{start=fn;return 1;};
  w.eval(script);
  return{w,d,card:d.getElementById('challenge-invite'),ready:()=>start(),close:()=>dom.window.close()};
}
let t=setup({oldDismissed:true});
assert.equal(t.d.getElementById('leader-challenge'),null,'old standalone block removed');
assert.match(t.card.querySelector('[data-open-drive]').textContent,/Выиграть бесплатный заезд/);
assert.ok(t.card.hidden,'not shown before delay');t.ready();
assert.ok(!t.card.hidden,'previous revision dismissal gets one new impression');
t.card.querySelector('[data-dismiss-invite]').click();assert.ok(t.card.hidden);
assert.equal(t.w.localStorage.getItem(key),'1');
t.w.dispatchEvent(new t.w.Event('scroll'));assert.ok(t.card.hidden,'closed card stays closed on scroll');t.close();
t=setup({newDismissed:true});t.ready();assert.ok(t.card.hidden,'new dismissal survives page or browser session reload');t.close();
t=setup();t.ready();t.d.dispatchEvent(new t.w.KeyboardEvent('keydown',{key:'Escape'}));assert.ok(t.card.hidden);assert.equal(t.w.localStorage.getItem(key),'1');t.close();
t=setup();t.ready();t.d.querySelector('#test-drive [data-open-drive]').click();assert.ok(t.card.hidden,'launching game dismisses invite');t.close();
t=setup();t.ready();t.w.dispatchEvent(new t.w.StorageEvent('storage',{key,newValue:'1'}));assert.ok(t.card.hidden,'dismissal in another tab respected');t.close();
t=setup();t.d.querySelector('dialog').setAttribute('open','');t.ready();assert.ok(t.card.hidden,'no overlay on open dialog');t.close();
t=setup();t.d.getElementById('prices').getBoundingClientRect=()=>({height:200,top:0,bottom:200});t.ready();assert.ok(t.card.hidden,'no overlay while booking');t.close();
t=setup({storageBlocked:true});t.ready();assert.ok(!t.card.hidden);t.card.querySelector('[data-dismiss-invite]').click();assert.ok(t.card.hidden,'still closable without browser storage');t.close();
console.log('PASS invitation: one-time revision reset, persistent close, Escape, game launch, cross-tab, booking/dialog suppression, storage unavailable');

